import { FieldDef, ResourceDef } from './resource.types';

// ---------------------------------------------------------------------------
// Field builders (keep definitions short & consistent)
// ---------------------------------------------------------------------------
type O = Partial<FieldDef>;
const text = (name: string, label: string, o: O = {}): FieldDef => ({ name, label, type: 'text', max: 150, ...o });
const code = (o: O = {}): FieldDef => text('code', 'Code', { required: true, max: 30, list: true, sortable: true, ...o });
const name = (o: O = {}): FieldDef => text('name', 'Name', { required: true, list: true, sortable: true, ...o });
const area = (n: string, label: string, o: O = {}): FieldDef => ({ name: n, label, type: 'textarea', max: 2000, wide: true, ...o });
const email = (o: O = {}): FieldDef => ({ name: 'email', label: 'Email', type: 'email', max: 150, ...o });
const phone = (o: O = {}): FieldDef => ({ name: 'phone', label: 'Phone', type: 'phone', max: 50, ...o });
const num = (n: string, label: string, o: O = {}): FieldDef => ({ name: n, label, type: 'number', ...o });
const int = (n: string, label: string, o: O = {}): FieldDef => ({ name: n, label, type: 'integer', ...o });
const money = (n: string, label: string, o: O = {}): FieldDef => ({ name: n, label, type: 'money', min: 0, ...o });
const pct = (n: string, label: string, o: O = {}): FieldDef => ({ name: n, label, type: 'percent', min: 0, max: 100, ...o });
const date = (n: string, label: string, o: O = {}): FieldDef => ({ name: n, label, type: 'date', ...o });
const dt = (n: string, label: string, o: O = {}): FieldDef => ({ name: n, label, type: 'datetime', ...o });
const bool = (n: string, label: string, o: O = {}): FieldDef => ({ name: n, label, type: 'boolean', default: false, ...o });
const active = (): FieldDef => bool('isActive', 'Active', { default: true, list: true, filter: true });
const rel = (n: string, label: string, resource: string, o: O = {}): FieldDef => ({ name: n, label, type: 'relation', relation: { resource }, ...o });
const lookup = (n: string, label: string, category: string, o: O = {}): FieldDef => ({ name: n, label, type: 'lookup', lookup: category, max: 50, ...o });
const select = (n: string, label: string, options: string[], o: O = {}): FieldDef => ({
  name: n,
  label,
  type: 'select',
  options: options.map((v) => ({ value: v, label: v.charAt(0) + v.slice(1).toLowerCase().replace(/_/g, ' ') })),
  ...o,
});
const secret = (n: string, label: string, o: O = {}): FieldDef => text(n, label, { encrypted: true, max: 100, ...o });

const simple = (key: string, model: string, module: string, label: string, singular: string, permission: string, extra: FieldDef[] = [], o: Partial<ResourceDef> = {}): ResourceDef => ({
  key,
  model,
  module,
  label,
  singular,
  permission,
  scope: 'company',
  fields: [code({ max: 20 }), name(), ...extra, active()],
  searchFields: ['code', 'name'],
  labelFields: ['code', 'name'],
  defaultSort: { field: 'code', order: 'asc' },
  ...o,
});

